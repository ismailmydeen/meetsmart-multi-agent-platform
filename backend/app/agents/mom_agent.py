"""
MoM Agent
---------
Post-meeting, drafts a formal Minutes of Meeting (MoM) Word document from
the meeting's structured notes (summary + action items), saves it to
samples/ with a date-stamped filename, and "emails" it to all participants
(stubbed unless EMAIL_ENABLED=true, same convention as the Invite Agent).
"""
import os
import json
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.base import MIMEBase
from email import encoders
from datetime import datetime

from docx import Document
from docx.shared import Pt, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
from sqlalchemy.orm import Session

from ..models import Meeting, ActionItem

SAMPLES_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "..", "samples")
SAMPLES_DIR = os.path.abspath(SAMPLES_DIR)


def generate_mom_docx(meeting: Meeting, action_items: list) -> str:
    """Build a formal MoM Word document for the meeting. Returns the file path."""
    os.makedirs(SAMPLES_DIR, exist_ok=True)

    structured = {}
    if meeting.notes_structured:
        try:
            structured = json.loads(meeting.notes_structured)
        except json.JSONDecodeError:
            structured = {}
    summary = structured.get("summary", "No summary available.")

    doc = Document()

    # Title
    title = doc.add_heading("Minutes of Meeting", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Meta table
    table = doc.add_table(rows=4, cols=2)
    table.style = "Light Grid Accent 1"
    meta_rows = [
        ("Meeting Title", meeting.title),
        ("Date", meeting.start_time.strftime("%d %B %Y")),
        ("Time", f"{meeting.start_time.strftime('%H:%M')} - {meeting.end_time.strftime('%H:%M')}"),
        ("Organizer", meeting.organizer_email),
    ]
    for i, (label, value) in enumerate(meta_rows):
        table.rows[i].cells[0].text = label
        table.rows[i].cells[0].paragraphs[0].runs[0].bold = True
        table.rows[i].cells[1].text = value

    doc.add_paragraph()

    # Attendees
    doc.add_heading("Attendees", level=1)
    for email in meeting.participant_emails.split(","):
        doc.add_paragraph(email.strip(), style="List Bullet")

    # Agenda
    if meeting.agenda:
        doc.add_heading("Agenda", level=1)
        doc.add_paragraph(meeting.agenda)

    # Summary
    doc.add_heading("Discussion Summary", level=1)
    doc.add_paragraph(summary)

    # Action items table
    doc.add_heading("Action Items", level=1)
    if action_items:
        items_table = doc.add_table(rows=1, cols=3)
        items_table.style = "Light Grid Accent 1"
        hdr = items_table.rows[0].cells
        hdr[0].text, hdr[1].text, hdr[2].text = "Action", "Owner", "Due Date"
        for cell in hdr:
            cell.paragraphs[0].runs[0].bold = True

        for item in action_items:
            row = items_table.add_row().cells
            row[0].text = item.description
            row[1].text = item.owner_email or "Unassigned"
            row[2].text = item.due_date.strftime("%d %b %Y") if item.due_date else "TBD"
    else:
        doc.add_paragraph("No action items recorded.")

    # Footer note
    doc.add_paragraph()
    footer = doc.add_paragraph(
        f"Generated by MeetSmart AI on {datetime.now().strftime('%d %B %Y %H:%M')}"
    )
    footer.runs[0].italic = True
    footer.runs[0].font.size = Pt(9)

    filename = f"MoM_meeting_{meeting.id}_{meeting.start_time.strftime('%Y%m%d')}.docx"
    filepath = os.path.join(SAMPLES_DIR, filename)
    doc.save(filepath)
    return filepath


def send_mom(meeting: Meeting, mom_path: str) -> dict:
    """Email the MoM doc to all participants. Stubbed unless EMAIL_ENABLED=true."""
    email_enabled = os.getenv("EMAIL_ENABLED", "false").lower() == "true"
    recipients = [e.strip() for e in meeting.participant_emails.split(",")]

    if not email_enabled:
        print(f"[STUB EMAIL] Would send MoM for '{meeting.title}' to {recipients}")
        print(f"[STUB EMAIL] Attachment: {mom_path}")
        return {"sent": False, "stubbed": True, "recipients": recipients, "mom_path": mom_path}

    smtp_host = os.getenv("SMTP_HOST")
    smtp_port = int(os.getenv("SMTP_PORT", "587"))
    smtp_user = os.getenv("SMTP_USER")
    smtp_pass = os.getenv("SMTP_APP_PASSWORD")

    msg = MIMEMultipart()
    msg["Subject"] = f"Minutes of Meeting: {meeting.title}"
    msg["From"] = smtp_user
    msg["To"] = ", ".join(recipients)
    msg.attach(MIMEText("Please find attached the Minutes of Meeting.", "plain"))

    with open(mom_path, "rb") as f:
        part = MIMEBase("application", "vnd.openxmlformats-officedocument.wordprocessingml.document")
        part.set_payload(f.read())
        encoders.encode_base64(part)
        part.add_header("Content-Disposition", f"attachment; filename={os.path.basename(mom_path)}")
        msg.attach(part)

    with smtplib.SMTP(smtp_host, smtp_port) as server:
        server.starttls()
        server.login(smtp_user, smtp_pass)
        server.sendmail(smtp_user, recipients, msg.as_string())

    return {"sent": True, "stubbed": False, "recipients": recipients, "mom_path": mom_path}


def create_and_send_mom(db: Session, meeting: Meeting) -> dict:
    action_items = db.query(ActionItem).filter(ActionItem.meeting_id == meeting.id).all()
    mom_path = generate_mom_docx(meeting, action_items)
    meeting.mom_path = mom_path
    db.commit()
    result = send_mom(meeting, mom_path)
    return result
